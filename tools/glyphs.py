#!/usr/bin/env python3
"""Rasterize the glyphs `bingo gif` draws with, into src/glyphs.zig.

    python3 tools/glyphs.py [FONT_DIR]

FONT_DIR holds the Inter typeface (default /usr/share/fonts/opentype/inter);
Inter is under the SIL Open Font License. Each glyph is stored as one hex
digit of coverage (0 to f) per pixel, row by row, with its offset from the
pen position on the baseline and its advance. Only this script needs the
fonts and Pillow; the build does not.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "glyphs.zig")
TEXT = "".join(chr(c) for c in range(32, 127)) + "·×"

# (name, file, pixel size, characters)
FONTS = [
    ("tile", "Inter-Bold.otf", 19, "ABCDEFGHIJKLMNOPQRSTUVWXYZ★"),
    ("value", "Inter-SemiBold.otf", 9, "0123456789"),
    ("text", "Inter-Medium.otf", 15, TEXT),
    ("bold", "Inter-Bold.otf", 15, TEXT),
]


def glyph(font, ch):
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    adv = round(font.getlength(ch))
    w, h = max(0, right - left), max(0, bottom - top)
    if w == 0 or h == 0:
        return (0, 0, 0, 0, adv, "")
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
    px = "".join("0123456789abcdef"[min(15, (v + 8) // 17)] for v in img.tobytes())
    return (w, h, left, top, adv, px)


def main(font_dir):
    lines = [
        "//! Generated by tools/glyphs.py from the Inter typeface (SIL Open Font",
        "//! License); do not edit. One hex digit of coverage per pixel, row by row.",
        "",
        "pub const Glyph = struct {",
        "    /// The character, as a Unicode code point.",
        "    cp: u21,",
        "    w: u8,",
        "    h: u8,",
        "    /// Offset of the top-left pixel from the pen on the baseline.",
        "    x: i8,",
        "    y: i8,",
        "    adv: u8,",
        "    px: []const u8,",
        "};",
        "",
        "pub const Font = struct {",
        "    ascent: u8,",
        "    glyphs: []const Glyph,",
        "",
        "    pub fn get(f: *const Font, cp: u21) ?*const Glyph {",
        "        for (f.glyphs) |*g| {",
        "            if (g.cp == cp) return g;",
        "        }",
        "        return null;",
        "    }",
        "};",
        "",
    ]
    for name, file, size, chars in FONTS:
        font = ImageFont.truetype(os.path.join(font_dir, file), size)
        ascent = font.getmetrics()[0]
        lines.append(f"pub const {name} = Font{{ .ascent = {ascent}, .glyphs = &.{{")
        for ch in chars:
            w, h, x, y, adv, px = glyph(font, ch)
            lines.append(f'    .{{ .cp = {ord(ch)}, .w = {w}, .h = {h}, .x = {x}, .y = {y}, .adv = {adv}, .px = "{px}" }},')
        lines.append("} };")
        lines.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter")
